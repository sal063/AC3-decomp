#!/usr/bin/env python3
import sys

def main():
    out, pairs = sys.argv[1], sys.argv[2:]
    lines = ["// generated by tools/embed_spv.py -- do not edit", "#pragma once", "#include <cstddef>",
             "#include <cstdint>", ""]
    for pair in pairs:
        name, path = pair.split("=", 1)
        data = open(path, "rb").read()
        if len(data) % 4:
            sys.exit(f"{path}: not a whole number of words")
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        lines.append(f"inline constexpr uint32_t {name}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append(f"inline constexpr size_t {name}_size = sizeof({name});")
        lines.append("")
    new = "\n".join(lines) + "\n"
    try:
        if open(out).read() == new:
            return 0
    except OSError:
        pass
    open(out, "w").write(new)
    return 0

if __name__ == "__main__":
    sys.exit(main())
