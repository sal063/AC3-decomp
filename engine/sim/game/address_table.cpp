bool Game::call_address(u32 fn, u32 a0, u32 a1, u32 a2, u32 a3, u32& out) {
    u32 r[34] = {};
    r[4] = a0;
    r[5] = a1;
    r[6] = a2;
    r[7] = a3;
    r[28] = 0x800BCB74u;
    r[29] = sp;
    engine_miss_ = false;
    const u32 v = call_engine(fn, r);
    if (engine_miss_) return false;
    out = v;
    return true;
}

u32 Game::call_by_address(u32 fn, const char* what, u32 a0, u32 a1, u32 a2, u32 a3) {
    u32 v = 0;
    if (!call_address(fn, a0, a1, a2, a3, v)) unported(fn, what);
    return v;
}

